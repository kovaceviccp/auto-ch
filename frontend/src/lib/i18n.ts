export type TranslationKey = keyof typeof translations.de;

export function useT() {
  const lang = useLanguageStore((s: { lang: Lang }) => s.lang);
  return (key: TranslationKey): string => {
    const dict = translations[lang as "de" | "en"] as Record<string, string>;
    return dict[key] ?? (translations.de as Record<string, string>)[key] ?? key;
  };
}
